import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {mkdtemp,readFile,writeFile,rm,mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
import {transform} from 'esbuild';
const repo=fileURLToPath(new URL('../../../',import.meta.url));
const baseVersion='0.1.32';
const base=join(repo,`releases/dsh-inbox-sidebar-${baseVersion}.tgz`);
const output=join(repo,'outputs/dsh-polish-0.1.6');
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const expected='9571696b83ff652e81af9fcacec7723fe09d80f595b00c50bb6395a3306caeda';
const temporary=await mkdtemp(join(repo,'temp/polish-sidebar-motion-'));
try {
  const names=execFileSync('tar',['-tzf',base],{encoding:'utf8'}).trim().split('\n');
  assert.ok(names.every(name=>name.startsWith('package/')&&!name.split('/').includes('..')));
  execFileSync('tar',['-xzf',base,'-C',temporary]);
  const folder=join(temporary,'package');
  const manifest=JSON.parse(await readFile(join(folder,'package.json'),'utf8'));
  assert.equal(manifest.name,'dsh-inbox-sidebar');
  assert.equal(manifest.version,baseVersion);
  const clientFile=join(folder,'lib/client.js');
  const before=await readFile(clientFile,'utf8');
  assert.equal(sha(before),expected,'已发布侧栏代码发生变化，拒绝将其他版本或并行改动打包');
  const source=await readFile(new URL('../support/snooze-menu.jsx',import.meta.url),'utf8');
  const context=before.match(/function createInboxView\((\w+), stylesheet\) \{\s*const \{([^}]+)\} = \1;/);
  assert.ok(context,'找不到发布组件的 React 与 Hook 绑定');
  const hooks=Object.fromEntries(context[2].split(',').map(value=>{const [key,alias]=value.trim().split(/\s*:\s*/);return[key,alias??key];}));
  for(const hook of ['useRef','useState','useLayoutEffect'])assert.ok(hooks[hook]);
  const adapted=source.replace(/\b(useRef|useState|useLayoutEffect)\b/g,name=>hooks[name]);
  const compiled=await transform(adapted,{loader:'jsx',target:'es2022',jsxFactory:`${context[1]}.createElement`,jsxFragment:`${context[1]}.Fragment`});
  const start=before.indexOf('function SnoozeMenu(');
  const end=before.indexOf('function useShelfView(',start);
  assert.ok(start>=0&&end>start);
  const parent='void actions.snooze(snoozeTarget.row.id, until, order);\n            setSnoozeTarget(null);';
  assert.equal(before.split(parent).length,2,'提醒业务关闭入口变化，拒绝回补');
  const after=(before.slice(0,start)+compiled.code+'\n    '+before.slice(end))
    .replace(parent,'void actions.snooze(snoozeTarget.row.id, until, order);');
  await writeFile(clientFile,after);
  execFileSync(process.execPath,['--check',clientFile]);
  manifest.version=`${baseVersion}-polish.1`;
  manifest.files=[...manifest.files,'polish-motion-support.json'];
  await writeFile(join(folder,'package.json'),JSON.stringify(manifest,null,2)+'\n');
  const metadata={version:manifest.version,baseVersion,baseClientSha256:expected,clientSha256:sha(after),adapterSha256:sha(source),scope:'仅替换 SnoozeMenu 生命周期，并将提醒后的卸载交回该组件；保留 0.1.32 已发布的拖拽实现，不打包当前工作区未发布源码。'};
  await writeFile(join(folder,'polish-motion-support.json'),JSON.stringify(metadata,null,2)+'\n');
  const readme=await readFile(join(folder,'README.md'),'utf8');
  await writeFile(join(folder,'README.md'),readme+`\n\n## DSH Polish 动效兼容回补\n\n本包以已发布的 ${baseVersion} 为基础，仅让稍后提醒弹层在逻辑关闭后等待节点已有的有限动画结束再卸载。提醒操作仍立即执行，键盘焦点在逻辑关闭时恢复。没有动效时立即关闭。未包含工作区中其他未发布修改。\n`);
  const packed=JSON.parse(execFileSync('npm',['pack','--ignore-scripts','--json','--pack-destination',join(repo,'releases')],{cwd:folder,encoding:'utf8'}))[0];
  await mkdir(output,{recursive:true});
  await writeFile(join(output,'sidebar-support-build.json'),JSON.stringify({...metadata,archive:packed.filename,archiveSha256:sha(await readFile(join(repo,'releases',packed.filename))),archiveBytes:packed.size},null,2)+'\n');
  console.log(JSON.stringify({...metadata,archive:packed.filename,archiveBytes:packed.size},null,2));
} finally {await rm(temporary,{recursive:true,force:true});}
